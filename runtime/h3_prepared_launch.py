"""Fixed-signature host launch for a kernel generated entirely by NineToothed.

Preparation compiles/executes the actual NineToothed kernel once. Replays launch
that same kernel and perform every numerical operation again. Only host tensor
metadata is retained; input values and generated outputs are never cached.

The adapter validates CUDA/HIP tensors, current device, dtype, shape and strides.
It then supplies their current device pointers to the compiled launcher, avoiding
repeated vendor pointer-attribute queries for already validated torch tensors.
Uses pinned NineToothed 0.26 and Triton host interfaces; no device code is written.
"""
import types

import torch


def _spec(tensor):
    if not isinstance(tensor, torch.Tensor) or not tensor.is_cuda:
        raise TypeError('Prepared NineToothed launch requires CUDA/HIP torch tensors')
    return tuple(tensor.shape), tuple(tensor.stride()), tensor.dtype, tensor.device


class _CaptureLaunch:
    def __init__(self, original):
        self.original = original

    def __getitem__(self, grid):
        def capture(*args, **kwargs):
            self.compiled = self.original[grid](*args, **kwargs)
            dimensions = tuple(grid(kwargs) if callable(grid) else grid)
            self.grid = dimensions + (1,) * (3 - len(dimensions))
            self.arguments = tuple(args)
            return self.compiled
        return capture


class PreparedNineToothed:
    def __init__(self, handle, *tensors):
        self.specs = tuple(_spec(t) for t in tensors)
        if len({id(t) for t in tensors}) != len(tensors):
            raise ValueError('Prepare with distinct tensor objects')
        if len({t.device for t in tensors}) != 1:
            raise ValueError('All tensors must be on the same device')
        self.device_index = tensors[0].device.index
        if torch.cuda.current_device() != self.device_index:
            raise ValueError('Select the tensor device before preparation')
        namespace = dict(handle._launch.__globals__)
        names = [name for name, value in namespace.items() if value is handle._kernel]
        if len(names) != 1:
            raise RuntimeError('Unexpected NineToothed generated host interface')
        capture = _CaptureLaunch(handle._kernel)
        namespace[names[0]] = capture
        # Clone generated host code instead of mutating shared module globals.
        generated = handle._launch
        recording_launch = types.FunctionType(generated.__code__, namespace,
                                               generated.__name__, generated.__defaults__,
                                               generated.__closure__)
        recording_launch(*tensors)
        if capture.compiled is None:
            raise RuntimeError('NineToothed did not return a compiled kernel')
        self.launcher = capture.compiled[capture.grid]
        tensor_ids = {id(t): index for index, t in enumerate(tensors)}
        self.arguments = list(capture.arguments)
        self.pointer_positions = []
        for position, argument in enumerate(capture.arguments):
            if isinstance(argument, torch.Tensor):
                if id(argument) not in tensor_ids:
                    raise RuntimeError('Unexpected tensor generated by host metadata code')
                self.pointer_positions.append((position, tensor_ids[id(argument)]))
                self.arguments[position] = None

    def __call__(self, *tensors):
        if len(tensors) != len(self.specs):
            raise ValueError('Prepared signature tensor count changed')
        if torch.cuda.current_device() != self.device_index:
            raise ValueError('Current device differs from the prepared kernel device')
        if tuple(_spec(t) for t in tensors) != self.specs:
            raise ValueError('Prepared signature dtype/device/shape/strides changed')
        arguments = self.arguments.copy()
        for position, tensor_index in self.pointer_positions:
            arguments[position] = tensors[tensor_index].data_ptr()
        # Inputs remain strongly referenced throughout this synchronous host call.
        # The caller retains normal stream/lifetime responsibility, as for torch ops.
        return self.launcher(*arguments)

    def _launch_native_pointers(self, pointers, stream):
        """Internal path after the C++ bridge checks the complete signature."""
        if len(pointers) != len(self.specs) or any(type(p) is not int or p <= 0 for p in pointers):
            raise ValueError('Invalid native tensor pointers')
        if type(stream) is not int or stream < 0:raise ValueError('Invalid native stream')
        if torch.cuda.current_device() != self.device_index:
            raise ValueError('Current device differs from the prepared kernel device')
        arguments=self.arguments.copy()
        for position,tensor_index in self.pointer_positions:
            arguments[position]=pointers[tensor_index]
        # Triton 3.8's CompiledKernel runner accepts an explicit stream. This
        # launches the Nine-generated kernel on the actual native worker stream.
        return self.launcher(*arguments,stream=stream)
